// The type-level test of T88.1: every generated type must be assignable to its `@csp/shared`
// twin and back. `tsc -b` fails here when a Rust type drifts from the TypeScript one. T88.2 deletes
// this file together with `@csp/shared`.
//
// Three kinds of line: `twin` (assignable both ways: the types are equal); a `twin` against
// `Omit<..., 'kind'>` (the Rust order struct has no `kind`: the tag sits on `ResidentOrder`,
// where the TypeScript lists it twice); and `tsFitsRust` (a difference noted in the PR: every
// TypeScript value is a Rust one, not the other way round).
import type * as Rust from './index.js'
import type * as Ts from '@csp/shared'

type Mutual<A, B> = [A] extends [B] ? ([B] extends [A] ? true : false) : false
declare function twin<A, B>(...differs: Mutual<A, B> extends true ? [] : ['the two differ']): void
declare function tsFitsRust<A, B>(
  ...differs: [B] extends [A] ? [] : ['the TypeScript type is not a Rust one']
): void

