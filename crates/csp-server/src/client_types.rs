/// Every `.ts` file in `dir`, by name, with line endings as LF.
fn read_dir_lf(dir: &Path) -> io::Result<BTreeMap<String, String>> {
    let mut files = BTreeMap::new();
    if !dir.exists() {
        return Ok(files);
    }
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if path.extension().and_then(|e| e.to_str()) == Some("ts") {
            let name = path.file_name().and_then(|n| n.to_str()).unwrap_or_default().to_owned();
            files.insert(name, fs::read_to_string(&path)?.replace("\r\n", "\n"));
        }
    }
    Ok(files)
}

/// What differs between what the Rust types generate now and the files in `committed`: a line
/// per file that is missing, extra or changed; empty when the files are current.
pub fn stale_files(committed: &Path) -> io::Result<Vec<String>> {
    let fresh_dir = tempfile::tempdir()?;
    export_into(fresh_dir.path())?;
    let fresh = read_dir_lf(fresh_dir.path())?;
    let have = read_dir_lf(committed)?;
    let mut problems = Vec::new();
    for (name, text) in &fresh {
        match have.get(name) {
            None => problems.push(format!("{name}: missing")),
            Some(old) if old != text => problems.push(format!("{name}: changed")),
            Some(_) => {}
        }
    }
    for name in have.keys().filter(|n| !fresh.contains_key(*n)) {
        problems.push(format!("{name}: no longer generated"));
    }
    Ok(problems)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The generated package is current: `pnpm types:rust` writes it, this fails when it is not.
    #[test]
    fn the_generated_types_are_not_stale() {
        let dir = workspace_root().join(GENERATED_DIR);
        let problems = stale_files(&dir).unwrap();
        assert!(
            problems.is_empty(),
            "packages/shared-types is stale; run `pnpm types:rust`:\n{}",
            problems.join("\n")
        );
    }
}
