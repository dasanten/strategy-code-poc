//! The client's types, generated from the Rust crates with `ts-rs` (ADR 0030, T88.1): every
//! protocol and world type the client receives or sends, written into the workspace package
//! `packages/shared-types` (`@csp/shared-types`) by `pnpm types:rust`.
//!
//! The roots below are the types the client imports; `ts-rs` follows their fields and writes
//! every type they use too. A test fails when the files on disk differ from what the Rust types
//! now generate, so a changed type can't reach the client unannounced.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use ts_rs::{Config, TS};

/// Where the generated package keeps its files, from the workspace root.
pub const GENERATED_DIR: &str = "packages/shared-types/src/generated";

/// The workspace root, found from this crate's manifest directory.
pub fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// The config every export uses: 64-bit integers are JavaScript numbers (`serde_json` writes them
/// as such), and imports name `.js` files since the TypeScript packages use NodeNext resolution.
fn config(dir: &Path) -> Config {
    Config::new().with_large_int("number").with_import_extension(Some("js")).with_out_dir(dir)
}

macro_rules! roots {
    ($cfg:expr; $($ty:ty),* $(,)?) => {{
        $( <$ty as TS>::export_all($cfg)
            .map_err(|e| io::Error::other(format!("{}: {e}", stringify!($ty))))?; )*
    }};
}

/// Writes every client type, and an `index.ts` that re-exports each file, into `dir`.
pub fn export_into(dir: &Path) -> io::Result<()> {
    fs::create_dir_all(dir)?;
    client_roots(&config(dir))?;
    let names = generated_names(dir)?;
    add_missing_imports(dir, &names)?;
    let mut index = String::from(
        "// This file was generated by `pnpm types:rust` from the Rust crates. Do not edit it.\n\n",
    );
    for name in &names {
        index.push_str(&format!("export * from './{name}.js'\n"));
    }
    fs::write(dir.join("index.ts"), index)
}

/// The names of the types written into `dir`, sorted.
fn generated_names(dir: &Path) -> io::Result<Vec<String>> {
    let mut names: Vec<String> = fs::read_dir(dir)?
        .filter_map(Result::ok)
        .filter_map(|e| e.file_name().to_str().map(str::to_owned))
        .filter_map(|n| n.strip_suffix(".ts").map(str::to_owned))
        .filter(|n| n != "index")
        .collect();
    names.sort();
    Ok(names)
}

/// Adds the `import type` lines a file needs for a type written out as TypeScript text
/// (`#[ts(type = "...")]`), which `ts-rs` can't see into: any other generated type its code names
/// and doesn't import yet.
fn add_missing_imports(dir: &Path, names: &[String]) -> io::Result<()> {
    let known: BTreeSet<&str> = names.iter().map(String::as_str).collect();
    for name in names {
        let path = dir.join(format!("{name}.ts"));
        let text = fs::read_to_string(&path)?;
        let (imports, code): (Vec<&str>, Vec<&str>) =
            text.lines().partition(|l| l.starts_with("import type"));
        let mut used = BTreeSet::new();
        let mut in_comment = false;
        for line in &code {
            let trimmed = line.trim_start();
            if trimmed.starts_with("/*") {
                in_comment = true;
            }
            if in_comment || trimmed.starts_with("//") {
                in_comment = in_comment && !trimmed.contains("*/");
                continue;
            }
            let mut word = String::new();
            for ch in line.chars().chain(std::iter::once(' ')) {
                if ch.is_alphanumeric() || ch == '_' {
                    word.push(ch);
                } else {
                    if known.contains(word.as_str()) && word != *name {
                        used.insert(word.clone());
                    }
                    word.clear();
                }
            }
        }
        let missing: Vec<&String> = used
            .iter()
            .filter(|u| !imports.iter().any(|i| i.contains(&format!("{{ {u} }}"))))
            .collect();
        if missing.is_empty() {
            continue;
        }
        let mut out = String::new();
        let mut lines = text.lines();
        let header = lines.next().unwrap_or_default();
        out.push_str(header);
        out.push('\n');
        let mut all: Vec<String> = imports.iter().map(|s| s.to_string()).collect();
        all.extend(missing.iter().map(|m| format!("import type {{ {m} }} from \"./{m}.js\";")));
        all.sort();
        for i in &all {
            out.push_str(i);
            out.push('\n');
        }
        let rest: Vec<&str> = lines.filter(|l| !l.starts_with("import type")).collect();
        out.push_str(&rest.join("\n"));
        out.push('\n');
        fs::write(&path, out)?;
    }
    Ok(())
}

