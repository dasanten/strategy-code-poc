//! The content specs as the client reads them (T121.4): `packages/balance/src/specs.ts`, written by
//! `pnpm balance:rust` beside the balance numbers ([`crate::balance_export`]), so the client keeps
//! no list of building kinds, goods, vessels or machines of its own. Each table is typed against
//! the generated union of its kinds, so a kind the client's own records (colour, art) lack fails
//! its typecheck.

use serde_json::{json, Map, Value};

use crate::building_spec::{BuildMenu, Stands};
use crate::good_spec::{Gear, ProtectionKind};
use crate::world::{BuildingKind, Good, SiegeMachineKind, VesselKind};

/// The kinds' specs as plain data, each table keyed by name in the order of its enum.
pub fn specs_json() -> Value {
    let mut buildings = Map::new();
    for kind in BuildingKind::ALL {
        let s = kind.spec();
        let (stands, in_city_area, on_shore) = match s.stands {
            Stands::OnNode => ("onNode", false, false),
            Stands::OnPlains => ("onPlains", false, false),
            Stands::OffNodes { city_area, shore } => ("offNodes", city_area, shore),
            Stands::OwnRule => ("ownRule", false, false),
        };
        let room = s.housing_room.unwrap_or(0.0);
        buildings.insert(
            kind.name().into(),
            json!({
                "label": s.label,
                "purpose": s.purpose.replace("{housing}", &room.to_string()),
                "footprint": s.footprint,
                "stands": stands,
                "inCityArea": in_city_area,
                "onShore": on_shore,
                "sharesATile": s.shares_a_tile,
                "keepsGoods": s.keeps_goods,
                "buildMenu": s.build.map(|b| json!({ "group": b.menu.name(), "place": b.menu_place })),
                "processes": s.workplace.is_some_and(|w| w.processing.is_some()),
            }),
        );
    }
    let mut goods = Map::new();
    for good in Good::ALL {
        let s = good.spec();
        let (weapon, protection) = match s.gear {
            Some(Gear::Weapon(w)) => {
                (json!({ "twoHanded": w.two_handed, "shoots": w.shot.is_some() }), Value::Null)
            }
            Some(Gear::Protection(p)) => (
                Value::Null,
                json!(match p.kind {
                    ProtectionKind::Shield => "shield",
                    ProtectionKind::Armour => "armour",
                }),
            ),
            None => (Value::Null, Value::Null),
        };
        goods.insert(
            good.name().into(),
            json!({
                "label": s.label,
                "priced": s.base_price.is_some(),
                "weapon": weapon,
                "protection": protection,
            }),
        );
    }
    let mut vessels = Map::new();
    for kind in VesselKind::ALL {
        let s = kind.spec();
        vessels.insert(
            s.name.into(),
            json!({ "label": s.built_as.spec().label, "name": s.name, "builtAs": s.built_as.name() }),
        );
    }
    let mut machines = Map::new();
    for kind in SiegeMachineKind::ALL {
        let s = kind.spec();
        machines.insert(
            s.name.into(),
            json!({
                "label": s.built_as.spec().label,
                "name": s.name,
                "builtAs": s.built_as.name(),
                "crew": s.crew,
                "strength": s.strength,
            }),
        );
    }
    let groups: Vec<&str> = BuildMenu::ALL.iter().map(|m| m.name()).collect();
    json!({
        "BUILDING_SPECS": buildings,
        "BUILD_MENU_GROUPS": groups,
        "GOOD_SPECS": goods,
        "VESSEL_SPECS": vessels,
        "MACHINE_SPECS": machines,
    })
}

const HEADER: &str = "// Generated by `pnpm balance:rust` from the specs in crates/csp-shared (T121.4). Do not edit.

import type { BuildingKind, Good, SiegeMachineKind, VesselKind } from '@csp/shared-types'

/** A building kind as the client sees it (\\`BuildingSpec\\` in Rust). */
export interface BuildingSpec {
  /** What the game calls it. */
  label: string
  /** What it is for, in words, numbers filled in. */
  purpose: string
  /** Tiles along each side (\\`CONTEXT.md\\`: Footprint). */
  footprint: number
  /** Where it may stand (\\`CONTEXT.md\\`: Where buildings go). */
  stands: 'onNode' | 'onPlains' | 'offNodes' | 'ownRule'
  /** Only in a city's area, every tile of it. */
  inCityArea: boolean
  /** Only on the shore, touching Lake or Sea. */
  onShore: boolean
  /** Shares a tile with a building: roads and the sites of what moves off. */
  sharesATile: boolean
  /** Keeps goods in a storage of its own. */
  keepsGoods: boolean
  /** Its group of the Build menu and its place there, the first 1; null for a kind nobody builds. */
  buildMenu: { group: string; place: number } | null
  /** A workplace that turns goods into other goods. */
  processes: boolean
}

/** A good as the client sees it (\\`GoodSpec\\` in Rust). */
export interface GoodSpec {
  label: string
  /** Warehouses put a price on it: every good but Coins. */
  priced: boolean
  /** As a weapon, if it is one: whether it takes both hands, whether it shoots. */
  weapon: { twoHanded: boolean; shoots: boolean } | null
  /** The kind of protection it is, if it is any. */
  protection: 'shield' | 'armour' | null
}

/** A vessel kind: its label, its name and the site it is built as. */
export interface VesselSpec {
  label: string
  name: string
  builtAs: BuildingKind
}

/** A siege machine kind: as a vessel, with its crew and strength. */
export interface MachineSpec extends VesselSpec {
  crew: number
  strength: number
}
";

/// A table as a TypeScript `const`, typed against `ty`.
fn table(name: &str, value: &Value, ty: &str) -> String {
    let text = serde_json::to_string_pretty(value).expect("serialisable");
    format!("\nexport const {name} = {text} as const satisfies {ty}\n")
}

/// `packages/balance/src/specs.ts`.
pub fn specs_text() -> String {
    let specs = specs_json();
    let mut out = String::from(HEADER);
    out.push_str(&table(
        "BUILDING_SPECS",
        &specs["BUILDING_SPECS"],
        "Record<BuildingKind, BuildingSpec>",
    ));
    out.push_str(&table("BUILD_MENU_GROUPS", &specs["BUILD_MENU_GROUPS"], "readonly string[]"));
    out.push_str(&table("GOOD_SPECS", &specs["GOOD_SPECS"], "Record<Good, GoodSpec>"));
    out.push_str(&table("VESSEL_SPECS", &specs["VESSEL_SPECS"], "Record<VesselKind, VesselSpec>"));
    out.push_str(&table(
        "MACHINE_SPECS",
        &specs["MACHINE_SPECS"],
        "Record<SiegeMachineKind, MachineSpec>",
    ));
    let names = |v: &Value| -> String {
        let keys: Vec<String> = v.as_object().unwrap().keys().map(|k| format!("'{k}'")).collect();
        keys.join(", ")
    };
    out.push_str(&format!(
        "\n/** Every building kind, in the order of the specs. */\nexport const BUILDING_KINDS = [{}] as const satisfies readonly BuildingKind[]\n",
        names(&specs["BUILDING_SPECS"])
    ));
    out.push_str(&format!(
        "\n/** Every good, in the order of the specs (`CONTEXT.md`: Good). */\nexport const GOOD_KINDS = [{}] as const satisfies readonly Good[]\n",
        names(&specs["GOOD_SPECS"])
    ));
    out
}
