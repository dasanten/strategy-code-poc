//! The balance JSON the client reads (ADR 0030, T88.4): every number of [`crate::balance`] plus the
//! few the Wiki also needs from `time`, `terrain` and `footprint`, written to `packages/balance/`
//! by `pnpm balance:rust` (`src/bin/write-balance.rs`).
//!
//! Three files, all generated from [`export_json`] and never edited:
//!
//! - `balance.json`: the numbers, keyed by their TypeScript names;
//! - `balance.d.ts`: the `Balance` interface, written from the same value so the two cannot differ;
//! - `src/constants.ts`: one named export per number, which is what the client imports.
//!
//! `tests/balance_export.rs` fails when a file on disk is not what this module writes now.

use serde_json::{json, Map, Value};

use crate::balance::balance_json;
use crate::footprint::FOOTPRINT;
use crate::terrain::{Terrain, DIAGONAL_STEP};
use crate::time::{
    GAME_DAYS_PER_YEAR, TICKS_PER_GAME_DAY, TICKS_PER_GAME_HOUR, TICKS_PER_GAME_YEAR,
};
use crate::TICK_MS;

/// Where the files go, relative to the workspace root.
pub const OUT_DIR: &str = "packages/balance";

/// The numbers of `balance.rs` (the table `balance.ts` has, checked against it by
/// `balance::tests`) and the time, terrain and footprint numbers the Wiki reads.
pub fn export_json() -> Value {
    let Value::Object(mut m) = balance_json() else {
        unreachable!("balance_json is an object");
    };
    let mut terrain = Map::new();
    for t in [
        Terrain::Plains,
        Terrain::Forest,
        Terrain::Hills,
        Terrain::Mountain,
        Terrain::Lake,
        Terrain::Sea,
        Terrain::Road,
    ] {
        terrain.insert(format!("{t:?}"), json!(t as u8));
    }
    let extras = [
        ("TERRAIN", Value::Object(terrain)),
        ("TICK_MS", json!(TICK_MS)),
        ("TICKS_PER_GAME_DAY", json!(TICKS_PER_GAME_DAY)),
        ("TICKS_PER_GAME_HOUR", json!(TICKS_PER_GAME_HOUR)),
        ("TICKS_PER_GAME_YEAR", json!(TICKS_PER_GAME_YEAR)),
        ("GAME_DAYS_PER_YEAR", json!(GAME_DAYS_PER_YEAR)),
        ("DIAGONAL_STEP", json!(DIAGONAL_STEP)),
        ("FOOTPRINT", serde_json::to_value(FOOTPRINT).expect("serialisable")),
    ];
    for (key, value) in extras {
        assert!(m.insert(key.to_string(), value).is_none(), "{key} is in the balance table too");
    }
    Value::Object(m)
}

/// `balance.json`: two-space indent, a final newline.
pub fn json_text() -> String {
    let mut text = serde_json::to_string_pretty(&export_json()).expect("serialisable");
    text.push('\n');
    text
}

const HEADER: &str =
    "// Generated by `pnpm balance:rust` from crates/csp-shared (ADR 0030). Do not edit.\n";

fn is_identifier(key: &str) -> bool {
    let mut chars = key.chars();
    chars.next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

/// The members of a union, once each, in order of first appearance.
fn union(types: impl Iterator<Item = String>) -> String {
    let mut seen: Vec<String> = Vec::new();
    for t in types {
        if !seen.contains(&t) {
            seen.push(t);
        }
    }
    seen.join(" | ")
}

/// The TypeScript type of a value. Objects are tables as much as structs (a good, a building kind
/// or a terrain keys them), so each keeps its own keys and takes any other key too, as the
/// union of its values: indexing by a name the table does not list gives `undefined`, as it does
/// in the game. Lists are arrays of the union of their items. Nothing is `readonly`: the
/// TypeScript constants were not, and the Wiki's tests change them to see a figure follow.
fn ts_type(value: &Value, indent: usize) -> String {
    match value {
        Value::Number(_) => "number".into(),
        Value::String(_) => "string".into(),
        Value::Bool(_) => "boolean".into(),
        Value::Null => "null".into(),
        Value::Array(items) => {
            let item = union(items.iter().map(|v| ts_type(v, indent)));
            if item.is_empty() {
                "never[]".into()
            } else if item.contains(' ') {
                format!("({item})[]")
            } else {
                format!("{item}[]")
            }
        }
        Value::Object(map) if map.is_empty() => "Record<string, never>".into(),
        Value::Object(map) => {
            let pad = "  ".repeat(indent + 1);
            let mut out = String::from("{\n");
            for (key, v) in map {
                let name = if is_identifier(key) { key.clone() } else { format!("'{key}'") };
                out.push_str(&format!(
                    "{pad}{name}: {}
",
                    ts_type(v, indent + 1)
                ));
            }
            let any = union(map.values().map(|v| ts_type(v, indent + 1)));
            out.push_str(&format!(
                "{pad}[key: string]: {any}
"
            ));
            out.push_str(&"  ".repeat(indent));
            out.push('}');
            out
        }
    }
}

/// `balance.d.ts`: the shape of `balance.json`.
pub fn dts_text() -> String {
    let value = export_json();
    let Value::Object(map) = &value else { unreachable!("an object") };
    let mut out = String::from(HEADER);
    out.push_str("\n/** The shape of `balance.json`: every number the client reads. */\n");
    out.push_str("export interface Balance {\n");
    for (key, v) in map {
        out.push_str(&format!("  readonly {key}: {}\n", ts_type(v, 1)));
    }
    out.push_str("}\n");
    out
}

/// `src/constants.ts`: each number as a named export, so the client writes
/// `import { ADULT_AGE } from '@csp/balance'` as it did from `@csp/shared`.
pub fn constants_text() -> String {
    let value = export_json();
    let Value::Object(map) = &value else { unreachable!("an object") };
    let mut out = String::from(HEADER);
    out.push_str("import type { Balance } from '../balance.js'\n");
    out.push_str("import data from '../balance.json'\n\n");
    out.push_str("/** The whole table, as written by Rust. */\n");
    // `Balance` is written from the same value, so the cast cannot hide a difference; the types
    // TypeScript infers from the JSON alone are too narrow for a list of different objects.
    out.push_str("export const balance = data as unknown as Balance\n\n");
    for key in map.keys() {
        out.push_str(&format!("export const {key} = balance.{key}\n"));
    }
    out
}

/// The files `pnpm balance:rust` writes, as (path from the workspace root, text).
pub fn files() -> Vec<(String, String)> {
    vec![
        (format!("{OUT_DIR}/balance.json"), json_text()),
        (format!("{OUT_DIR}/balance.d.ts"), dts_text()),
        (format!("{OUT_DIR}/src/constants.ts"), constants_text()),
    ]
}
