// Exports the pixel art in `art/pixel/*.aseprite` to what the web app loads (`docs/art.md`: Pixel
// art): per sheet a PNG of the art and a PNG of its `tint` layer if it has one, and in
// `apps/web/src/map/pixel-slices.ts` where each named slice lies. The resident's layers come out
// side by side as one PNG, each layer a slice of its own. Needs Aseprite: set ASEPRITE to its
// executable if it isn't found.
import { execFileSync } from 'node:child_process'
import console from 'node:console'
import process from 'node:process'
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const SOURCE = 'art/pixel'
const OUT = 'apps/web/src/assets/pixel'
/** Where each named slice lies, as a module the web app imports. */
const SLICES = 'apps/web/src/map/pixel-slices.ts'
const SHEETS = ['buildings', 'tiles', 'units', 'goods', 'ui']
/** The file whose layers stack into one figure. */
const LAYERED = 'resident'

const candidates = [
  process.env.ASEPRITE,
  'C:/Program Files/Aseprite/Aseprite.exe',
  'C:/Program Files (x86)/Steam/steamapps/common/Aseprite/Aseprite.exe',
  'D:/SteamLibrary/steamapps/common/Aseprite/Aseprite.exe',
  '/Applications/Aseprite.app/Contents/MacOS/aseprite',
  '/usr/bin/aseprite',
]
const aseprite = candidates.find((p) => p && existsSync(p))
if (!aseprite) {
  console.error('Aseprite not found; set ASEPRITE to its executable.')
  process.exit(1)
}
const run = (...args) => execFileSync(aseprite, ['-b', ...args], { stdio: 'pipe' })

mkdirSync(OUT, { recursive: true })
const scratch = mkdtempSync(join(tmpdir(), 'pixel-art-'))
const sheets = {}
try {
  for (const name of SHEETS) {
    const file = join(SOURCE, `${name}.aseprite`)
    const data = join(scratch, `${name}.json`)
    run('--list-slices', '--list-layers', file, '--data', data, '--sheet', join(scratch, 'x.png'))
    const exported = JSON.parse(readFileSync(data, 'utf8'))
    const { w, h } = Object.values(exported.frames)[0].sourceSize
    const layers = exported.meta.layers.map((l) => l.name)
    // Everything but the guide and the tint is art, so extra art layers need no change here.
    const notArt = layers.filter((l) => l.startsWith('guide') || l === 'tint')
    run(
      ...notArt.flatMap((l) => ['--ignore-layer', l]),
      '--frame-range',
      '0,0',
      file,
      '--save-as',
      join(OUT, `${name}.png`),
    )
    const tint = join(OUT, `${name}-tint.png`)
    if (layers.includes('tint'))
      run('--layer', 'tint', '--frame-range', '0,0', file, '--save-as', tint)
    else rmSync(tint, { force: true })
    sheets[name] = {
      size: [w, h],
      tint: layers.includes('tint'),
      slices: Object.fromEntries(
        exported.meta.slices
          .map((s) => [s.name, s.keys[0].bounds])
          .sort(([a], [b]) => a.localeCompare(b))
          .map(([n, b]) => [n, [b.x, b.y, b.w, b.h]]),
      ),
    }
  }

  const file = join(SOURCE, `${LAYERED}.aseprite`)
  const data = join(scratch, `${LAYERED}.json`)
  run(
    '--split-layers',
    '--frame-range',
    '0,0',
    file,
    '--filename-format',
    '{layer}',
    '--sheet-type',
    'horizontal',
    '--sheet',
    join(OUT, `${LAYERED}.png`),
    '--data',
    data,
  )
  const layered = JSON.parse(readFileSync(data, 'utf8'))
  sheets[LAYERED] = {
    size: [layered.meta.size.w, layered.meta.size.h],
    tint: false,
    slices: Object.fromEntries(
      Object.entries(layered.frames).map(([layer, f]) => [
        layer,
        [f.frame.x, f.frame.y, f.frame.w, f.frame.h],
      ]),
    ),
  }
} finally {
  rmSync(scratch, { recursive: true, force: true })
}

writeFileSync(
  SLICES,
  [
    "// Generated by scripts/pixel-art.mjs from art/pixel; don't edit by hand.",
    '',
    '/** Each exported sheet: its size, whether it has a tint image, and its slices as [x, y, w, h]. */',
    `export const PIXEL_SLICES = ${JSON.stringify(sheets)} as const`,
    '',
  ].join('\n'),
)
execFileSync(process.execPath, ['node_modules/prettier/bin/prettier.cjs', '--write', SLICES], {
  stdio: 'inherit',
})
for (const [name, sheet] of Object.entries(sheets))
  console.log(`${name}: ${Object.keys(sheet.slices).length} slices${sheet.tint ? ', tint' : ''}`)
